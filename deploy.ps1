#requires -version 5.1
<#
.SYNOPSIS
    One-command Docker deployment for PRAgent.

.DESCRIPTION
    Creates a .env with strong random secrets (when missing), builds the image,
    starts postgres + redis + pragent, waits for the /health endpoint and prints
    the dashboard URL with the bootstrap credentials.

.PARAMETER Port
    Host port for the dashboard. Defaults to PRAGENT_HTTP_PORT in .env, else 8080.

.PARAMETER Recreate
    Regenerate .env with fresh secrets. The previous file is kept as a timestamped
    backup. Postgres keeps its initialised password, so pair this with
    `docker volume rm pragent_postgres_data` if you also rotate the DB password.

.PARAMETER NoBuild
    Skip the image build and reuse the existing pragent:local image.

.PARAMETER PipIndexUrl
    pip index passed as a build arg (useful for a regional mirror).

.PARAMETER PythonImage
    Base image for the build. Defaults to python:3.11-slim; override it when a
    local image (for example python:3.12-slim) is already present.

.EXAMPLE
    pwsh -File deploy.ps1

.EXAMPLE
    pwsh -File deploy.ps1 -Port 9080 -PipIndexUrl https://pypi.tuna.tsinghua.edu.cn/simple
#>
[CmdletBinding()]
param(
    [int]$Port = 0,
    [switch]$Recreate,
    [switch]$NoBuild,
    [string]$PipIndexUrl = "",
    [string]$PythonImage = ""
)

Set-StrictMode -Version Latest
$ErrorActionPreference = "Stop"
Set-Location -LiteralPath $PSScriptRoot

$envPath = Join-Path $PSScriptRoot ".env"

function New-SecretText {
    param([int]$Length)
    $bytes = New-Object byte[] $Length
    $rng = [System.Security.Cryptography.RandomNumberGenerator]::Create()
    try { $rng.GetBytes($bytes) } finally { $rng.Dispose() }
    $text = [Convert]::ToBase64String($bytes).Replace("+", "-").Replace("/", "_").TrimEnd("=")
    if ($text.Length -lt $Length) { return $text }
    return $text.Substring(0, $Length)
}

function Get-DotEnvValue {
    param([string]$Path, [string]$Key)
    if (-not (Test-Path -LiteralPath $Path)) { return "" }
    foreach ($line in [System.IO.File]::ReadAllLines($Path)) {
        $trimmed = $line.Trim()
        if (-not $trimmed -or $trimmed.StartsWith("#")) { continue }
        $parts = $trimmed.Split("=", 2)
        if ($parts.Count -ne 2) { continue }
        if ($parts[0].Trim() -eq $Key) {
            return $parts[1].Trim().Trim("'").Trim('"')
        }
    }
    return ""
}

function Write-DotEnv {
    param([string]$Path, [string]$AdminPassword, [string]$DbPassword, [string]$AuthSecret, [int]$HttpPort)
    $lines = @(
        "# Generated by deploy.ps1 on $(Get-Date -Format 'yyyy-MM-dd HH:mm:ss'). Keep this file private.",
        "# Add model / GitHub settings from .env.example below, then run: docker compose up -d",
        "",
        "PRAGENT_HTTP_PORT=$HttpPort",
        "PRAGENT_PUBLIC_BASE_URL=http://127.0.0.1:$HttpPort",
        "",
        "PRAGENT_AUTH_REQUIRED=true",
        "PRAGENT_AUTH_SECRET=$AuthSecret",
        "PRAGENT_BOOTSTRAP_ADMIN_USERNAME=admin",
        "PRAGENT_BOOTSTRAP_ADMIN_PASSWORD=$AdminPassword",
        "",
        "# Postgres credentials. Changing this after the first start requires",
        "# removing the pragent_postgres_data volume.",
        "PRAGENT_POSTGRES_PASSWORD=$DbPassword",
        "",
        "# local | deepseek | openrouter-deepseek-free | openrouter-free | custom",
        "PRAGENT_LLM_PROVIDER=local",
        "PRAGENT_DEEPSEEK_API_KEY=",
        "PRAGENT_OPENROUTER_API_KEY=",
        "",
        "PRAGENT_GITHUB_WEBHOOK_SECRET=",
        "PRAGENT_GITHUB_TOKEN=",
        "PRAGENT_AUTO_POST_REVIEW=false"
    )
    $encoding = New-Object System.Text.UTF8Encoding($false)
    [System.IO.File]::WriteAllText($Path, ($lines -join "`n") + "`n", $encoding)
}

function Invoke-Compose {
    param([string[]]$Arguments)
    & $script:composeExe @($script:composePrefix + $Arguments)
    if ($LASTEXITCODE -ne 0) {
        throw "docker compose $($Arguments -join ' ') failed with exit code $LASTEXITCODE"
    }
}

if (-not (Get-Command docker -ErrorAction SilentlyContinue)) {
    throw "Docker CLI not found. Install Docker Desktop and start it, then re-run this script."
}

$composeCommand = $null
& docker compose version *> $null
if ($LASTEXITCODE -eq 0) {
    $composeCommand = @("docker", "compose")
} else {
    if (Get-Command docker-compose -ErrorAction SilentlyContinue) {
        $composeCommand = @("docker-compose")
    } else {
        throw "Neither 'docker compose' nor 'docker-compose' is available."
    }
}

& docker info *> $null
if ($LASTEXITCODE -ne 0) {
    throw "Docker daemon is not reachable. Start Docker Desktop (or the docker service) and retry."
}

$composeExe = $composeCommand[0]
$composePrefix = @()
if ($composeCommand.Count -gt 1) { $composePrefix = $composeCommand[1..($composeCommand.Count - 1)] }

$effectivePort = $Port
if ($effectivePort -le 0) {
    $effectivePort = 8080
    $fromEnv = Get-DotEnvValue -Path $envPath -Key "PRAGENT_HTTP_PORT"
    if ($fromEnv) { $effectivePort = [int]$fromEnv }
} else {
    # An explicit -Port must win over a stale .env; shell environment beats the
    # .env file in compose interpolation, so the mapping and the probe agree.
    $env:PRAGENT_HTTP_PORT = "$effectivePort"
    $env:PRAGENT_PUBLIC_BASE_URL = "http://127.0.0.1:$effectivePort"
}

$envExists = Test-Path -LiteralPath $envPath
$adminPassword = ""
if ($envExists -and $Recreate) {
    $backup = "$envPath.bak.$((Get-Date).ToString('yyyyMMddHHmmss'))"
    Copy-Item -LiteralPath $envPath -Destination $backup
    Write-Host "Backed up existing .env to $backup"
    $envExists = $false
}

if (-not $envExists) {
    $adminPassword = New-SecretText -Length 24
    Write-DotEnv -Path $envPath `
        -AdminPassword $adminPassword `
        -DbPassword (New-SecretText -Length 32) `
        -AuthSecret (New-SecretText -Length 32) `
        -HttpPort $effectivePort
    Write-Host "Wrote $envPath with freshly generated secrets."
} else {
    $adminPassword = Get-DotEnvValue -Path $envPath -Key "PRAGENT_BOOTSTRAP_ADMIN_PASSWORD"
    Write-Host "Reusing existing $envPath (use -Recreate to regenerate secrets)."
    if ((Get-DotEnvValue -Path $envPath -Key "PRAGENT_AUTH_SECRET").Length -lt 32) {
        throw "PRAGENT_AUTH_SECRET in .env is shorter than 32 bytes. Re-run with -Recreate."
    }
}

$upArgs = @("up", "-d", "--remove-orphans")
if (-not $NoBuild) {
    $upArgs = @("up", "-d", "--build", "--remove-orphans")
    if ($PipIndexUrl) { $env:PIP_INDEX_URL = $PipIndexUrl }
    if ($PythonImage) { $env:PYTHON_IMAGE = $PythonImage }
}

Write-Host "Starting stack: $($composeCommand -join ' ') $($upArgs -join ' ')"
Invoke-Compose -Arguments $upArgs

$healthUrl = "http://127.0.0.1:$effectivePort/health"
Write-Host "Waiting for $healthUrl ..."
$ready = $false
$deadline = (Get-Date).AddSeconds(180)
while ((Get-Date) -lt $deadline) {
    try {
        $response = Invoke-WebRequest -Uri $healthUrl -UseBasicParsing -TimeoutSec 3
        if ($response.StatusCode -eq 200) { $ready = $true; break }
    } catch {
        Start-Sleep -Seconds 2
    }
}

$adminUser = Get-DotEnvValue -Path $envPath -Key "PRAGENT_BOOTSTRAP_ADMIN_USERNAME"
if (-not $adminUser) { $adminUser = "admin" }

if (-not $ready) {
    Write-Warning "Service did not become healthy within 180s. Recent logs:"
    & $composeExe @($composePrefix + @("logs", "--tail", "60", "pragent"))
    throw "Health check failed. Inspect the logs above."
}

Write-Host ""
Write-Host "PRAgent is up."
Write-Host "  Dashboard : http://127.0.0.1:$effectivePort/"
Write-Host "  Health    : $healthUrl"
Write-Host "  Username  : $adminUser"
Write-Host "  Password  : $adminPassword"
Write-Host ""
Write-Host "Follow logs : $($composeCommand -join ' ') logs -f pragent"
Write-Host "Stop stack  : $($composeCommand -join ' ') down"
Write-Host "Model keys  : edit .env (see .env.example), then $($composeCommand -join ' ') up -d"

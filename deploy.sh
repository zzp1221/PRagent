#!/usr/bin/env bash
# One-command Docker deployment for PRAgent (Linux / macOS).
#
# Creates a .env with strong random secrets (when missing), builds the image,
# starts postgres + redis + pragent, waits for /health and prints the dashboard
# URL with the bootstrap credentials.
#
# Usage:
#   ./deploy.sh                       # build + start + verify
#   ./deploy.sh --port 9080           # custom host port
#   ./deploy.sh --no-build            # reuse the existing pragent:local image
#   ./deploy.sh --recreate            # regenerate .env secrets (backs up the old file)
#   ./deploy.sh --pip-index https://pypi.tuna.tsinghua.edu.cn/simple
#   ./deploy.sh --python-image python:3.12-slim   # reuse an already-pulled base
set -euo pipefail

cd "$(dirname "$0")"

ENV_FILE=".env"
PORT=""
RECREATE=0
NO_BUILD=0
PIP_INDEX=""
PYTHON_IMAGE=""

while [ $# -gt 0 ]; do
  case "$1" in
    --port) PORT="${2:?--port needs a value}"; shift 2 ;;
    --pip-index) PIP_INDEX="${2:?--pip-index needs a value}"; shift 2 ;;
    --python-image) PYTHON_IMAGE="${2:?--python-image needs a value}"; shift 2 ;;
    --recreate) RECREATE=1; shift ;;
    --no-build) NO_BUILD=1; shift ;;
    -h|--help) sed -n '2,15p' "$0" | sed 's/^# \{0,1\}//'; exit 0 ;;
    *) echo "unknown argument: $1" >&2; exit 2 ;;
  esac
done

command -v docker >/dev/null 2>&1 || {
  echo "Docker CLI not found. Install Docker Engine / Docker Desktop first." >&2
  exit 1
}

if docker compose version >/dev/null 2>&1; then
  COMPOSE=(docker compose)
elif command -v docker-compose >/dev/null 2>&1; then
  COMPOSE=(docker-compose)
else
  echo "Neither 'docker compose' nor 'docker-compose' is available." >&2
  exit 1
fi

docker info >/dev/null 2>&1 || {
  echo "Docker daemon is not reachable. Start it and retry." >&2
  exit 1
}

secret() {
  local length="$1" raw
  if command -v openssl >/dev/null 2>&1; then
    raw="$(openssl rand -base64 48 | tr '+/' '-_' | tr -d '=\n')"
  else
    raw="$(head -c 48 /dev/urandom | base64 | tr '+/' '-_' | tr -d '=\n')"
  fi
  printf '%s' "${raw:0:length}"
}

env_get() {
  local key="$1"
  [ -f "$ENV_FILE" ] || return 0
  awk -v k="$key" '
    { sub(/\r$/, "") }
    /^[[:space:]]*#/ { next }
    {
      line = $0
      eq = index(line, "=")
      if (eq == 0) next
      name = substr(line, 1, eq - 1)
      gsub(/^[[:space:]]+|[[:space:]]+$/, "", name)
      if (name != k) next
      value = substr(line, eq + 1)
      gsub(/^[[:space:]]+|[[:space:]]+$/, "", value)
      gsub(/^["\047]|["\047]$/, "", value)
      print value
      exit
    }
  ' "$ENV_FILE"
}

if [ -z "$PORT" ]; then
  PORT="$(env_get PRAGENT_HTTP_PORT)"
  [ -n "$PORT" ] || PORT=8080
else
  # An explicit --port must win over a stale .env; the shell environment beats
  # the .env file in compose interpolation, so mapping and probe stay in sync.
  export PRAGENT_HTTP_PORT="$PORT"
  export PRAGENT_PUBLIC_BASE_URL="http://127.0.0.1:$PORT"
fi

if [ -f "$ENV_FILE" ] && [ "$RECREATE" -eq 1 ]; then
  backup="${ENV_FILE}.bak.$(date +%Y%m%d%H%M%S)"
  cp "$ENV_FILE" "$backup"
  echo "Backed up existing .env to $backup"
  rm -f "$ENV_FILE"
fi

ADMIN_PASSWORD=""
if [ ! -f "$ENV_FILE" ]; then
  ADMIN_PASSWORD="$(secret 24)"
  cat > "$ENV_FILE" <<EOF
# Generated by deploy.sh on $(date '+%Y-%m-%d %H:%M:%S'). Keep this file private.
# Add model / GitHub settings from .env.example below, then run: docker compose up -d

PRAGENT_HTTP_PORT=$PORT
PRAGENT_PUBLIC_BASE_URL=http://127.0.0.1:$PORT

PRAGENT_AUTH_REQUIRED=true
PRAGENT_AUTH_SECRET=$(secret 32)
PRAGENT_BOOTSTRAP_ADMIN_USERNAME=admin
PRAGENT_BOOTSTRAP_ADMIN_PASSWORD=$ADMIN_PASSWORD

# Postgres credentials. Changing this after the first start requires removing
# the pragent_postgres_data volume.
PRAGENT_POSTGRES_PASSWORD=$(secret 32)

# local | deepseek | openrouter-deepseek-free | openrouter-free | custom
PRAGENT_LLM_PROVIDER=local
PRAGENT_DEEPSEEK_API_KEY=
PRAGENT_OPENROUTER_API_KEY=

PRAGENT_GITHUB_WEBHOOK_SECRET=
PRAGENT_GITHUB_TOKEN=
PRAGENT_AUTO_POST_REVIEW=false
EOF
  chmod 600 "$ENV_FILE" 2>/dev/null || true
  echo "Wrote $ENV_FILE with freshly generated secrets."
else
  ADMIN_PASSWORD="$(env_get PRAGENT_BOOTSTRAP_ADMIN_PASSWORD)"
  echo "Reusing existing $ENV_FILE (use --recreate to regenerate secrets)."
  auth_secret="$(env_get PRAGENT_AUTH_SECRET)"
  if [ "${#auth_secret}" -lt 32 ]; then
    echo "PRAGENT_AUTH_SECRET in .env is shorter than 32 bytes. Re-run with --recreate." >&2
    exit 1
  fi
fi

UP_ARGS=(up -d --remove-orphans)
if [ "$NO_BUILD" -eq 0 ]; then
  UP_ARGS=(up -d --build --remove-orphans)
  if [ -n "$PIP_INDEX" ]; then
    export PIP_INDEX_URL="$PIP_INDEX"
  fi
  if [ -n "$PYTHON_IMAGE" ]; then
    export PYTHON_IMAGE
  fi
fi

echo "Starting stack: ${COMPOSE[*]} ${UP_ARGS[*]}"
"${COMPOSE[@]}" "${UP_ARGS[@]}"

HEALTH_URL="http://127.0.0.1:${PORT}/health"
echo "Waiting for $HEALTH_URL ..."
ready=0
for _ in $(seq 1 90); do
  if curl -fsS -m 3 "$HEALTH_URL" >/dev/null 2>&1; then
    ready=1
    break
  fi
  sleep 2
done

ADMIN_USER="$(env_get PRAGENT_BOOTSTRAP_ADMIN_USERNAME)"
[ -n "$ADMIN_USER" ] || ADMIN_USER=admin

if [ "$ready" -ne 1 ]; then
  echo "Service did not become healthy within 180s. Recent logs:" >&2
  "${COMPOSE[@]}" logs --tail 60 pragent >&2 || true
  exit 1
fi

cat <<EOF

PRAgent is up.
  Dashboard : http://127.0.0.1:${PORT}/
  Health    : ${HEALTH_URL}
  Username  : ${ADMIN_USER}
  Password  : ${ADMIN_PASSWORD}

Follow logs : ${COMPOSE[*]} logs -f pragent
Stop stack  : ${COMPOSE[*]} down
Model keys  : edit .env (see .env.example), then ${COMPOSE[*]} up -d
EOF
